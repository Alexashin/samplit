"""Samplit palette: OKLCH ramps -> semantic tokens (light/dark), hex output, contrast check."""
import json
from coloraide import Color

def ok(L, C, H):
    return Color("oklch", [L, C, H]).convert("srgb").fit("srgb", method="oklch-chroma")

def hexs(c):
    return c.convert("srgb").to_string(hex=True, upper=False)

def contrast(fg, bg):
    return round(Color(fg).contrast(Color(bg), method="wcag21"), 2)

H_N, H_A = 265, 268
# step: (L, chroma) ; neutral ramp tinted toward the accent hue, accent ramp tapers at both ends
neutral = {50:(.975,.004),100:(.955,.006),200:(.915,.008),300:(.86,.010),400:(.74,.014),
           500:(.62,.018),600:(.52,.020),700:(.43,.022),800:(.33,.022),900:(.25,.022),950:(.19,.024)}
accent  = {50:(.965,.020),100:(.935,.040),200:(.890,.080),300:(.830,.135),400:(.730,.200),
           500:(.620,.250),600:(.530,.265),700:(.460,.245),800:(.390,.205),900:(.320,.150),950:(.240,.100)}
ramps = {"neutral": {k: hexs(ok(L, C, H_N)) for k,(L,C) in neutral.items()},
         "accent":  {k: hexs(ok(L, C, H_A)) for k,(L,C) in accent.items()}}
N, A = ramps["neutral"], ramps["accent"]

def status(h, name):
    return {
      "light": {f"{name}-text": hexs(ok(.45,.12 if name!="crit" else .17,h)),
                f"{name}-soft": hexs(ok(.955,.04,h)),
                f"{name}-solid": hexs(ok(.56,.15,h))},
      "dark":  {f"{name}-text": hexs(ok(.80,.13,h)),
                f"{name}-soft": hexs(ok(.30,.05,h)),
                f"{name}-solid": hexs(ok(.68,.15,h))}}
st = [status(155,"ok"), status(78,"warn"), status(25,"crit")]

light = {"bg": N[100], "surface": N[50], "pad": N[200], "line": N[300],
         "text": N[950], "text-muted": N[700],
         "accent": A[600], "accent-hover": A[700], "on-accent": "#ffffff",
         "accent-soft": A[100], "accent-text": A[700], "focus": A[600]}
dark  = {"bg": hexs(ok(.165,.016,H_N)), "surface": hexs(ok(.205,.018,H_N)), "pad": hexs(ok(.255,.020,H_N)),
         "line": hexs(ok(.32,.022,H_N)), "text": N[100], "text-muted": hexs(ok(.74,.016,H_N)),
         "accent": A[400], "accent-hover": A[300], "on-accent": N[950],
         "accent-soft": hexs(ok(.30,.09,H_A)), "accent-text": A[300], "focus": A[400]}
for s in st:
    light.update(s["light"]); dark.update(s["dark"])

tokens = {"ramps": ramps, "light": light, "dark": dark}
json.dump(tokens, open("tokens.json","w"), indent=2)

# ---- contrast report
pairs = [("text","bg"),("text","surface"),("text-muted","bg"),("text-muted","surface"),("on-accent","accent"),
         ("accent-text","bg"),("accent-text","accent-soft"),("accent","bg"),("line","bg"),
         ("ok-text","ok-soft"),("warn-text","warn-soft"),("crit-text","crit-soft"),("ok-text","bg"),("warn-text","bg")]
rep = []
for theme, t in (("light",light),("dark",dark)):
    for fg,bg in pairs:
        rep.append((theme,fg,bg,contrast(t[fg],t[bg])))
for r in rep: print(*r)
json.dump(rep, open("contrast.json","w"))

# ---- css
def block(sel, t):
    return sel+" {\n"+"\n".join(f"  --{k}: {v};" for k,v in t.items())+"\n}\n"
css = "/* Samplit tokens. Generated by build_tokens.py */\n"+block(":root", light)
css += "@media (prefers-color-scheme: dark) {\n"+block("  :root:not([data-theme=\"light\"])", dark).replace("\n  ","\n    ").replace("  :root","  :root",1)+"}\n"
css += block(":root[data-theme=\"dark\"]", dark)
open("tokens.css","w").write(css)
print(json.dumps({"accent":A, "neutral":N}, indent=0)[:900])
